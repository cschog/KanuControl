const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const output = process.env.KC_TEST_OUTPUT || path.join(__dirname, 'artifacts');
fs.mkdirSync(output, { recursive: true });
const { chromium } = require(process.env.KC_PLAYWRIGHT_MODULE || 'playwright');
(async () => {
 const browser = await chromium.launch({headless:true,channel:"chrome"});
 const context = await browser.newContext({viewport:{width:1200,height:900}});
 const page = await context.newPage(); const errors=[];
 page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:18765/?p=4');
 const root=page.locator('.kc-hp');
 await root.locator('form').waitFor({state:'visible'});
 const calendar=page.locator('.kc-calendar');
 await calendar.locator('.kc-calendar-message').filter({hasText:'Aktuelle Belegung aus KC.'}).waitFor();
 assert.equal(await calendar.locator('[data-status=BELEGT] small').first().textContent(),'2027-001');
 assert.equal(await calendar.locator('a[data-status=BELEGT]').count(),0);
 await calendar.locator('select').selectOption('11');
 await calendar.getByRole('button',{name:'Nächster Monat',exact:true}).click();
 await calendar.locator('.kc-calendar-message').filter({hasText:'Aktuelle Belegung aus KC.'}).waitFor();
 const href=await calendar.locator('a.kc-calendar-day').first().getAttribute('href');
 const expectedArrival=new URL(href).searchParams.get('kc_anreise');
 await calendar.locator('a.kc-calendar-day').first().click();
 await root.locator('form').waitFor({state:'visible'});
 assert.equal(await root.locator('input[name="anreise"]').inputValue(),expectedArrival);
 assert.equal(await root.getByRole('checkbox',{name:'Auswählen Schlafräume und Bad im OG',exact:true}).isChecked(),true);
 assert.equal(await root.getByRole('checkbox',{name:'Auswählen Bootshaus EG einschließlich Wiese',exact:true}).isChecked(),true);
 assert.equal(await root.locator('.kc-hp-submit').isDisabled(),true);
 await root.locator('input[name="anreise"]').fill('2027-07-10');
 await root.locator('input[name="abreise"]').fill('2027-07-12');
 assert.equal(await root.locator('input[name="abreise"]').getAttribute('min'),'2027-07-11');
 await root.getByRole('checkbox',{name:'Auswählen Schlafräume und Bad im OG',exact:true}).check();
 assert.equal(await root.getByRole('checkbox',{name:'Auswählen Bootshaus EG einschließlich Wiese',exact:true}).isChecked(),true);
 assert.equal(await root.locator('.kc-hp-resources input[type=number]').count(),1);
 await root.getByRole('spinbutton',{name:'Anzahl Gruppengrill',exact:true}).fill('2');
 await root.getByRole('checkbox',{name:'Auswählen Schlafräume und Bad im OG',exact:true}).uncheck();
 assert.equal(await root.getByRole('checkbox',{name:'Auswählen Schlafräume und Bad im OG',exact:true}).isChecked(),false);
 await root.getByRole('checkbox',{name:'Auswählen Schlafräume und Bad im OG',exact:true}).check();
 const checkedRequest=page.waitForRequest(r=>r.method()==='POST' && (r.url().includes('verfuegbarkeit')));
 await root.getByRole('button',{name:'Verfügbarkeit prüfen',exact:true}).click();
 assert.deepEqual((await checkedRequest).postDataJSON().auswahl.positionen,[{mietbereichId:10,anzahl:1},{mietbereichId:11,anzahl:1},{mietbereichId:12,anzahl:2}]);
 await root.getByRole('button',{name:'Anfrage absenden',exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=>!document.querySelector('.kc-hp-submit').disabled);
 await root.locator('input[name="anzahlJugendliche"]').fill('8');
 assert.equal(await root.locator('input[name="jugendAlterVon"]').isEnabled(),true);
 await root.locator('input[name="jugendAlterVon"]').fill('12');
 await root.locator('input[name="jugendAlterBis"]').fill('16');
 await root.locator('input[name="anzahlErwachsene"]').fill('2');
 assert.equal(await root.locator('.kc-hp-total').textContent(),'Teilnehmer gesamt: 10');
 await root.screenshot({path:path.join(output, 'Homepage-Formular-Vorschau.png')});
 for(const [name,value] of Object.entries({vorname:'Test',name:'Browsergast',email:'gast@example.test',emailWiederholung:'gast@example.test',telefon:'0123456789',strasse:'Teststraße 1',plz:'12345',ort:'Testort'})) await root.locator('[name="'+name+'"]').fill(value);
 await root.locator('[name="hausregelnAkzeptiert"]').check(); await root.locator('[name="datenschutzGelesen"]').check();
 await root.getByRole('button',{name:'Anfrage absenden',exact:true}).click();
 await root.locator('.kc-hp-message').filter({hasText:'Deine Anfrage ist in KC eingegangen'}).waitFor();
 assert.equal(await root.locator('form').isHidden(),true);
 await page.reload();
 await root.locator('.kc-hp-message').filter({hasText:'Deine Anfrage ist in KC eingegangen'}).waitFor();
 assert.equal(await root.locator('form').isHidden(),true);
 const mobile = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const phone=await mobile.newPage(); await phone.goto('http://127.0.0.1:18765/?p=4');
 await phone.locator('.kc-hp form').waitFor({state:'visible'});
 assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await phone.locator('.kc-calendar-message').filter({hasText:'Aktuelle Belegung aus KC.'}).waitFor();
 await phone.locator('.kc-calendar').screenshot({path:path.join(output,'Homepage-Kalender-Mobil.png')});
 await phone.locator('.kc-hp').screenshot({path:path.join(output, 'Homepage-Formular-Mobil.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS Desktop, automatische Bereichsvoraussetzung, Verfügbarkeit, Teilnehmerdaten, Absenden, Schutz bei Neuladen und mobile Darstellung.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
